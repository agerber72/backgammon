/// The legal texts in `assets/legal/` use a small part of Markdown: headings,
/// bullets, bold, code and platform sections. This file reads them without
/// Flutter, so that the app and the tools for the web pages share one source.
library;

/// The platforms a legal text can address separately.
enum LegalPlatform { android, windows, web }

final _sectionStart = RegExp(r'^<!--\s*nur:\s*(.+?)\s*-->$');
final _sectionEnd = RegExp(r'^<!--\s*ende\s*-->$');

/// The lines of [text] meant for [platform]. Lines between
/// `<!-- nur: android, windows -->` and `<!-- ende -->` belong only to the
/// platforms named there; any other comment is left out.
List<String> legalLines(String text, LegalPlatform platform) {
  final lines = <String>[];
  Set<String>? only;
  var inComment = false;
  for (final line in text.split('\n')) {
    final clean = line.trim();
    if (inComment) {
      inComment = !clean.endsWith('-->');
      continue;
    }
    final section = _sectionStart.firstMatch(clean);
    if (section != null) {
      only = section.group(1)!.split(',').map((name) => name.trim()).toSet();
      continue;
    }
    if (_sectionEnd.hasMatch(clean)) {
      only = null;
      continue;
    }
    if (clean.startsWith('<!--')) {
      inComment = !clean.endsWith('-->');
      continue;
    }
    if (only == null || only.contains(platform.name)) {
      lines.add(line);
    }
  }
  return lines;
}

/// A complete, self-contained web page for the text as the web version sees
/// it. It loads nothing from other servers.
String legalHtml(String text, {required String title, required String back}) {
  final body = StringBuffer();
  final paragraph = <String>[];
  var inList = false;

  void closeParagraph() {
    if (paragraph.isNotEmpty) {
      body.writeln('<p>${paragraph.join('<br>\n')}</p>');
      paragraph.clear();
    }
  }

  void closeList() {
    if (inList) {
      body.writeln('</ul>');
      inList = false;
    }
  }

  for (final line in legalLines(text, LegalPlatform.web)) {
    final clean = line.trim();
    if (clean.isEmpty) {
      closeParagraph();
      closeList();
    } else if (clean.startsWith('# ')) {
      closeParagraph();
      closeList();
      body.writeln('<h1>${_inline(clean.substring(2))}</h1>');
    } else if (clean.startsWith('## ')) {
      closeParagraph();
      closeList();
      body.writeln('<h2>${_inline(clean.substring(3))}</h2>');
    } else if (clean.startsWith('- ')) {
      closeParagraph();
      if (!inList) {
        body.writeln('<ul>');
        inList = true;
      }
      body.writeln('<li>${_inline(clean.substring(2))}</li>');
    } else {
      closeList();
      paragraph.add(_inline(clean));
    }
  }
  closeParagraph();
  closeList();

  return '''
<!DOCTYPE html>
<!-- Generated by tools/legal/build_pages.dart from assets/legal/. Do not edit. -->
<html lang="de">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${_escape(title)}</title>
<style>
:root { color-scheme: light dark; --text: #1a1a1a; --muted: #5f6368;
  --background: #ffffff; --accent: #1f4d3a; }
@media (prefers-color-scheme: dark) {
  :root { --text: #e8eaed; --muted: #9aa0a6; --background: #17191c;
    --accent: #8fd3b4; }
}
body { margin: 0; background: var(--background); color: var(--text);
  font: 16px/1.6 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }
main { max-width: 42rem; margin: 0 auto; padding: 24px 16px 48px; }
h1 { font-size: 1.75rem; line-height: 1.25; margin: 0 0 16px; }
h2 { font-size: 1.2rem; margin: 32px 0 8px; }
a { color: var(--accent); overflow-wrap: anywhere; }
code { font-size: 0.9em; overflow-wrap: anywhere; }
nav { margin-bottom: 24px; color: var(--muted); }
</style>
</head>
<body>
<main>
<nav><a href="${_escape(back)}">Zurück zur App</a></nav>
${body.toString().trimRight()}
</main>
</body>
</html>
''';
}

String _escape(String text) => text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

final _bold = RegExp(r'\*\*(.+?)\*\*');
final _code = RegExp('`(.+?)`');
final _link = RegExp(r'https://[^\s<]+[^\s<.,;:)]');
final _mail = RegExp(r'[\w.+-]+@[\w-]+(\.[\w-]+)+');

String _inline(String text) => _escape(text)
    .replaceAllMapped(_bold, (match) => '<strong>${match[1]}</strong>')
    .replaceAllMapped(_code, (match) => '<code>${match[1]}</code>')
    .replaceAllMapped(_link, (match) => '<a href="${match[0]}">${match[0]}</a>')
    .replaceAllMapped(
      _mail,
      (match) => '<a href="mailto:${match[0]}">${match[0]}</a>',
    );
